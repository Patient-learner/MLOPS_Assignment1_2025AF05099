"""
Production FastAPI Model Serving API.
Exposes /predict, /health, and Prometheus /metrics endpoints.
"""

import time
from contextlib import asynccontextmanager
from fastapi import FastAPI, HTTPException, Request, Response
from fastapi.responses import PlainTextResponse
from prometheus_client import CONTENT_TYPE_LATEST, Counter, Histogram, generate_latest

from src.api.schemas import HealthResponse, PatientData, PredictionResponse
from src.models.predict import HeartDiseasePredictor
from src.utils.logger import setup_logger

logger = setup_logger("api")

# Prometheus Metrics Definitions
HTTP_REQUESTS_TOTAL = Counter(
    "http_requests_total",
    "Total HTTP requests handled by the service",
    ["method", "endpoint", "status_code"],
)
REQUEST_LATENCY_SECONDS = Histogram(
    "request_latency_seconds",
    "Request latency in seconds",
    ["endpoint"],
    buckets=(0.005, 0.01, 0.025, 0.05, 0.1, 0.25, 0.5, 1.0, 2.5),
)
PREDICTIONS_TOTAL = Counter(
    "heart_disease_predictions_total",
    "Total number of predictions generated by model",
    ["prediction_label"],
)

# Global model predictor instance
predictor: HeartDiseasePredictor = None


def get_predictor() -> HeartDiseasePredictor:
    """Returns or lazily initializes predictor engine."""
    global predictor
    if predictor is None:
        try:
            predictor = HeartDiseasePredictor()
        except Exception as e:
            logger.error(f"Failed to initialize predictor: {e}")
            raise HTTPException(status_code=503, detail="Model engine unavailable")
    return predictor


@asynccontextmanager
async def lifespan(app: FastAPI):
    """Lifespan context manager for loading model at startup."""
    global predictor
    logger.info("Initializing Heart Disease Inference Engine...")
    try:
        predictor = HeartDiseasePredictor()
        logger.info("Champion model successfully loaded into memory.")
    except Exception as e:
        logger.error(f"Failed to load model on startup: {e}")
    yield
    logger.info("Shutting down model serving service...")


app = FastAPI(
    title="Heart Disease Prediction API",
    description="Production-grade MLOps Serving API for Heart Disease Risk Classification (AIMLCZG523)",
    version="1.0.0",
    lifespan=lifespan,
)


@app.middleware("http")
async def prometheus_metrics_middleware(request: Request, call_next):
    """Middleware to track latency and status codes for Prometheus."""
    start_time = time.time()
    endpoint = request.url.path

    try:
        response = await call_next(request)
        status_code = response.status_code
    except Exception as e:
        status_code = 500
        raise e
    finally:
        latency = time.time() - start_time
        # Record metrics (ignore /metrics scrape to prevent skewing)
        if endpoint != "/metrics":
            HTTP_REQUESTS_TOTAL.labels(
                method=request.method, endpoint=endpoint, status_code=status_code
            ).inc()
            REQUEST_LATENCY_SECONDS.labels(endpoint=endpoint).observe(latency)

    return response


@app.get("/", tags=["General"])
def root():
    """Root landing endpoint."""
    return {
        "project": "MLOps Assignment 01 - Heart Disease Classifier",
        "bits_id": "2025AF05099",
        "author_id": "2025AF05099",
        "documentation": "/docs",
        "health": "/health",
        "metrics": "/metrics",
        "predict": "/predict",
    }


@app.get("/health", response_model=HealthResponse, tags=["Health"])
def health_check():
    """Liveness and readiness probe for Kubernetes and Docker."""
    engine = get_predictor()
    if engine is None or engine.model is None:
        raise HTTPException(status_code=503, detail="Model is not loaded")
    return {
        "status": "healthy",
        "model_loaded": True,
        "version": "1.0.0",
        "app_name": "heart-disease-classifier-api",
    }


@app.post("/predict", response_model=PredictionResponse, tags=["Inference"])
def predict(patient: PatientData):
    """
    Accepts clinical patient data in JSON format and returns
    binary prediction (0: No Disease, 1: Heart Disease) with probability and confidence.
    """
    engine = get_predictor()
    patient_dict = patient.model_dump()
    logger.info(f"Incoming prediction request: age={patient.age}, sex={patient.sex}, cp={patient.cp}")

    try:
        result = engine.predict(patient_dict)

        # Increment Prometheus counter
        PREDICTIONS_TOTAL.labels(prediction_label=result["label"]).inc()

        logger.info(
            f"Prediction completed: label='{result['label']}', prob={result['probability']}, conf={result['confidence']}"
        )
        return {
            "prediction": result["prediction"],
            "label": result["label"],
            "probability": result["probability"],
            "confidence": result["confidence"],
            "model_version": "1.0.0",
        }
    except Exception as e:
        logger.error(f"Inference computation error: {e}")
        raise HTTPException(status_code=500, detail=str(e))


@app.get("/metrics", response_class=PlainTextResponse, tags=["Monitoring"])
def metrics():
    """Exposes Prometheus formatted metrics for scrapers."""
    return Response(content=generate_latest(), media_type=CONTENT_TYPE_LATEST)
